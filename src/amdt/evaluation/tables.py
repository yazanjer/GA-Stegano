r"""LaTeX table emission with booktabs rules.

Tables are written to ``tables/*.tex`` and the manuscript should ``\input{}``
them, so re-running the pipeline updates the paper without anyone retyping a
number.  Every table carries a generated-on comment with the git commit and the
seed list, which is what lets a reviewer match a table to a run.

Conventions
-----------
* ``\toprule`` / ``\midrule`` / ``\bottomrule``, no vertical rules.
* ``mean $\pm$ std`` at a fixed precision per column.
* Best value per column in ``\textbf{}``; ties both bolded.
* Significance markers relative to the proposed method: ``*`` p<0.05,
  ``**`` p<0.01, ``***`` p<0.001, all **after** Holm correction, with the
  correction stated in the caption rather than buried in the text.
"""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Sequence

import numpy as np

__all__ = ["stars", "fmt_mean_std", "latex_table", "results_table",
           "significance_table", "runtime_table", "detection_table", "write_table"]


def stars(p: float) -> str:
    if not np.isfinite(p):
        return ""
    if p < 0.001:
        return r"$^{***}$"
    if p < 0.01:
        return r"$^{**}$"
    if p < 0.05:
        return r"$^{*}$"
    return ""


def fmt_mean_std(mean: float, std: float, prec: int = 2) -> str:
    if not np.isfinite(mean):
        return "--"
    return rf"{mean:.{prec}f} $\pm$ {std:.{prec}f}"


def _escape(s: str) -> str:
    for a, b in (("_", r"\_"), ("%", r"\%"), ("&", r"\&"), ("#", r"\#")):
        s = s.replace(a, b)
    return s


def latex_table(header: Sequence[str], rows: Sequence[Sequence[str]], caption: str,
                label: str, column_spec: Optional[str] = None,
                notes: Sequence[str] = (), provenance: str = "",
                small: bool = True) -> str:
    ncol = len(header)
    spec = column_spec or ("l" + "r" * (ncol - 1))
    lines = [
        f"% generated by amdt run_experiments.py on "
        f"{datetime.now(timezone.utc).isoformat(timespec='seconds')}",
    ]
    if provenance:
        lines.append(f"% {provenance}")
    lines += [
        r"\begin{table}[!t]",
        r"\centering",
        rf"\caption{{{caption}}}",
        rf"\label{{{label}}}",
    ]
    if small:
        lines.append(r"\footnotesize")
    lines += [
        rf"\begin{{tabular}}{{{spec}}}",
        r"\toprule",
        " & ".join(header) + r" \\",
        r"\midrule",
    ]
    lines += [" & ".join(r) + r" \\" for r in rows]
    lines += [r"\bottomrule", r"\end{tabular}"]
    for n in notes:
        lines.append(rf"\\[2pt] \parbox{{\linewidth}}{{\scriptsize {n}}}")
    lines.append(r"\end{table}")
    return "\n".join(lines) + "\n"


def write_table(text: str, out_dir: str | Path, name: str) -> Path:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    p = out / f"{name}.tex"
    p.write_text(text)
    return p


