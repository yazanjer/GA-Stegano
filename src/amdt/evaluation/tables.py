def results_table(per_method: Dict[str, Dict[str, Sequence[float]]],
                  metrics: Sequence[str] = ("psnr", "ssim", "mse", "embedding_efficiency"),
                  metric_labels: Optional[Dict[str, str]] = None,
                  precisions: Optional[Dict[str, int]] = None,
                  higher_is_better: Optional[Dict[str, bool]] = None,
                  p_values: Optional[Dict[str, Dict[str, float]]] = None,
                  caption: str = "Imperceptibility comparison (mean $\\pm$ std over the test set).",
                  label: str = "tab:quality",
                  provenance: str = "") -> str:
    labels = metric_labels or {
        "psnr": "PSNR (dB)", "ssim": "SSIM", "mse": "MSE",
        "embedding_efficiency": "Emb. eff. (bits/change)",
        "correlation": "Correlation",
    }
    prec = precisions or {"psnr": 2, "ssim": 4, "mse": 4,
                          "embedding_efficiency": 2, "correlation": 5}
    hib = higher_is_better or {"psnr": True, "ssim": True, "mse": False,
                               "embedding_efficiency": True, "correlation": True}

    header = ["Method"] + [labels.get(m, m) for m in metrics]
    means = {m: {k: float(np.nanmean(v[m])) for k, v in per_method.items() if m in v}
             for m in metrics}
    best = {}
    for m in metrics:
        if not means[m]:
            continue
        best[m] = (max if hib.get(m, True) else min)(means[m], key=means[m].get)

    rows = []
    for name, vals in per_method.items():
        cells = [_escape(name)]
        for m in metrics:
            if m not in vals:
                cells.append("--")
                continue
            a = np.asarray(vals[m], dtype=float)
            txt = fmt_mean_std(np.nanmean(a), np.nanstd(a, ddof=1) if a.size > 1 else 0.0,
                               prec.get(m, 3))
            if p_values and name in p_values and m in p_values[name]:
                txt += stars(p_values[name][m])
            if best.get(m) == name:
                txt = rf"\textbf{{{txt}}}"
            cells.append(txt)
        rows.append(cells)

    notes = [
        r"Best value per column in bold. Significance markers are versus the "
        r"proposed method using the paired test selected by a Shapiro--Wilk "
        r"check, with Holm--Bonferroni correction across the baseline family: "
        r"$^{*}p<0.05$, $^{**}p<0.01$, $^{***}p<0.001$.",
    ]
    return latex_table(header, rows, caption, label, notes=notes, provenance=provenance)


def significance_table(comparisons: Sequence, caption: str =
                       "Paired significance tests against the proposed method.",
                       label: str = "tab:significance", provenance: str = "") -> str:
    header = ["Comparison", "Metric", "$n$", r"$\Delta$ (95\% CI)",
              "$t$", "$p_t$", "$W$", "$p_W$", "$d_z$", r"$\delta$", "$p_{\\text{adj}}$"]
    rows = []
    for c in comparisons:
        rows.append([
            _escape(f"{c.method_a} vs {c.method_b}"),
            _escape(c.metric),
            str(c.n_pairs),
            rf"{c.mean_diff:.4g} [{c.diff_ci_low:.3g}, {c.diff_ci_high:.3g}]",
            f"{c.t_statistic:.3g}",
            f"{c.t_p_value:.2e}",
            f"{c.wilcoxon_statistic:.4g}",
            f"{c.wilcoxon_p_value:.2e}",
            f"{c.cohens_dz:.2f}",
            f"{c.cliffs_delta:.2f}",
            f"{c.p_adjusted:.2e}" + stars(c.p_adjusted),
        ])
    notes = [
        r"$\Delta$ is the mean paired difference (proposed $-$ baseline) with a "
        r"10{,}000-sample bootstrap CI. $d_z$ is Cohen's paired effect size, "
        r"$\delta$ is Cliff's delta. $p_{\text{adj}}$ is Holm--Bonferroni "
        r"corrected within the metric family.",
    ]
    return latex_table(header, rows, caption, label,
                       column_spec="ll" + "r" * 9, notes=notes, provenance=provenance)


def runtime_table(stage_rows: Sequence[Dict[str, object]],
                  caption: str = "Runtime profile and analytic complexity.",
                  label: str = "tab:runtime", provenance: str = "",
                  hardware: Optional[str] = None) -> str:
    """Runtime table, with a hardware column whenever rows span devices.

    A table where one row was timed on a laptop and another on a T4 is not a
    comparison.  If the rows disagree on hardware the column appears
    automatically; if they agree it goes in the caption instead of wasting a
    column.  Rows whose timings are invalid (hosted VM, MPS fallback, migrated
    run) are marked and named in the note rather than dropped, so the omission
    is visible.
    """
    labels = {str(r.get("hardware", "")) for r in stage_rows if r.get("hardware")}
    mixed = len(labels) > 1
    invalid = [r for r in stage_rows if r.get("timing_valid") is False]

    header = ["Stage", "$n$", "Mean (s)", "SD (s)", "Total (s)"]
    if mixed:
        header.append("Hardware")
    header += ["Time", "Space"]

    rows = []
    for r in stage_rows:
        flag = "" if r.get("timing_valid", True) else r"$^{\dagger}$"
        cells = [_escape(str(r["stage"])) + flag, str(int(r["n"])),
                 f"{r['wall_mean_s']:.4g}", f"{r['wall_std_s']:.2g}",
                 f"{r['wall_total_s']:.4g}"]
        if mixed:
            cells.append(_escape(str(r.get("hardware", "--"))))
        cells += [
            f"${_escape(str(r.get('complexity_time','')))}$" if r.get("complexity_time") else "--",
            f"${_escape(str(r.get('complexity_space','')))}$" if r.get("complexity_space") else "--",
        ]
        rows.append(cells)

    notes = [r"$N$ = cover pixels, $L$ = payload bits, $P$ = population, "
             r"$G$ = generations, $S$ = segments, $B$ = scrambling block size."]
    hw = hardware or (labels.pop() if len(labels) == 1 else None)
    if hw and not mixed:
        notes.append(rf"All timings measured on {_escape(hw)}.")
    if invalid:
        reasons = {str(r.get("timing_invalid_reason")) for r in invalid
                   if r.get("timing_invalid_reason")}
        notes.append(
            r"$^{\dagger}$ timings not comparable and excluded from any claim: "
            + _escape("; ".join(sorted(reasons)) or "unspecified") + ".")

    spec = "lrrrr" + ("l" if mixed else "") + "ll"
    return latex_table(header, rows, caption, label, column_spec=spec,
                       notes=notes, provenance=provenance)


def detection_table(rows_by_method: Dict[str, Dict[str, float]],
                    detector: str = "SRM-subset + FLD ensemble",
                    caption: Optional[str] = None,
                    label: str = "tab:detection",
                    provenance: str = "") -> str:
    header = ["Method", "Acc.", "Prec.", "Rec.", "F1", "AUC", "$P_E$", "MD@FA5\\%"]
    rows = []
    for name, m in rows_by_method.items():
        rows.append([
            _escape(name),
            f"{m['accuracy']:.3f}", f"{m['precision']:.3f}", f"{m['recall']:.3f}",
            f"{m['f1']:.3f}", f"{m['auc']:.3f}", f"{m['p_e']:.3f}",
            f"{m['md_at_fa5']:.3f}",
        ])
    cap = caption or (
        f"Steganalysis performance of the {detector} detector. "
        r"For a steganographic method \emph{lower} detector accuracy and "
        r"\emph{higher} $P_E$ are better; $P_E = 0.5$ means undetectable."
    )
    return latex_table(header, rows, cap, label, provenance=provenance)
